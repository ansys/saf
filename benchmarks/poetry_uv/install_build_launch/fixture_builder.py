"""Build the benchmark solution for one backend from the shared fixture.

The fixture is one SAF solution used by both backends:

* ``fixture/solution/``       README and source code, identical for Poetry and UV.
* ``fixture/dependencies.toml`` the only list of dependencies.
* ``fixture/poetry.lock`` and ``fixture/uv.lock`` locks with identical versions.

:func:`write_solution` copies the solution, writes the backend's
``pyproject.toml`` from ``dependencies.toml``, and adds the matching lock file.
The result is a normal SAF solution, so ``saf install``, ``saf build``, and the
installer run exactly as they would on a real project.

Run this script with ``--relock`` after editing ``dependencies.toml``: it
locks both backends, keeping the current versions where possible, and only
writes the locks when Poetry and UV resolved exactly the same versions.
``--check`` only verifies that the committed locks still match each other.

Only the standard library is used, so the WSL worker can import this module.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib

FIXTURE_DIRECTORY = Path(__file__).resolve().parent / "fixture"
BACKENDS = ("poetry", "uv")
LOCK_FILES = {"poetry": "poetry.lock", "uv": "uv.lock"}
PROJECT_NAME = "saf-solutions-benchmark-solution"
AUTHOR = "ANSYS, Inc."
AUTHOR_EMAIL = "solution-applications.maintainers@ansys.com"
COPY_EXCLUSIONS = shutil.ignore_patterns(
    ".venv", ".poetry", "dist", "__pycache__", "*.pyc", "*.egg-info", ".pytest_cache", ".mypy_cache", ".tox"
)
HEADER = "# Generated by fixture_builder.py from fixture/dependencies.toml. Do not edit.\n\n"

REQUIREMENT = re.compile(
    r"^\s*(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)\s*"
    r"(?:\[(?P<extras>[^\]]*)\])?\s*"
    r"(?P<specifier>[^;]*?)\s*"
    r"(?:;\s*(?P<marker>.+?))?\s*$",
)


@dataclass(frozen=True)
class Requirement:
    """One PEP 508 requirement from ``dependencies.toml``."""

    name: str
    extras: tuple[str, ...]
    specifier: str
    marker: str | None

    @classmethod
    def parse(cls, text: str) -> Requirement:
        """Parse ``name[extras] specifier; marker``."""
        match = REQUIREMENT.match(text)
        if match is None or not match.group("specifier"):
            raise ValueError(f"Unsupported requirement (a version specifier is required): {text!r}")
        extras = tuple(part.strip() for part in (match.group("extras") or "").split(",") if part.strip())
        return cls(match.group("name"), extras, match.group("specifier").replace(" ", ""), match.group("marker"))


@dataclass(frozen=True)
class Dependencies:
    """Content of ``dependencies.toml``."""

    requires_python: str
    poetry_version: str
    saf_cli_version: str
    groups: dict[str, list[Requirement]]

    @classmethod
    def load(cls, fixture: Path = FIXTURE_DIRECTORY) -> Dependencies:
        """Load and validate ``dependencies.toml``."""
        data = tomllib.loads((fixture / "dependencies.toml").read_text(encoding="utf-8"))
        solution = data["solution"]
        groups = {name: [Requirement.parse(item) for item in items] for name, items in data["dependencies"].items()}
        if "main" not in groups:
            raise ValueError("dependencies.toml must define a 'main' dependency list.")
        return cls(
            requires_python=str(solution["requires-python"]),
            poetry_version=str(solution["poetry-version"]),
            saf_cli_version=str(solution["saf-cli-version"]),
            groups=groups,
        )

    @property
    def optional_groups(self) -> dict[str, list[Requirement]]:
        """Return the dependency groups (everything except ``main``)."""
        return {name: items for name, items in self.groups.items() if name != "main"}


def toml_string(value: str) -> str:
    """Return a TOML basic string."""
    return json.dumps(value)


def pep508(requirement: Requirement) -> str:
    """Return the requirement as a PEP 508 string for UV."""
    extras = f"[{','.join(requirement.extras)}]" if requirement.extras else ""
    marker = f"; {requirement.marker}" if requirement.marker else ""
    return f"{requirement.name}{extras}{requirement.specifier}{marker}"


def poetry_value(requirement: Requirement) -> str:
    """Return the requirement as a Poetry dependency value."""
    if not requirement.extras and not requirement.marker:
        return toml_string(requirement.specifier)
    fields = [f"version = {toml_string(requirement.specifier)}"]
    if requirement.extras:
        fields.append(f"extras = [{', '.join(toml_string(extra) for extra in requirement.extras)}]")
    if requirement.marker:
        fields.append(f"markers = {toml_string(requirement.marker)}")
    return "{ " + ", ".join(fields) + " }"


def poetry_pyproject(dependencies: Dependencies) -> str:
    """Return the Poetry ``pyproject.toml``."""
    lines = [
        "[build-system]",
        'requires = ["poetry-core>=2.0.0", "setuptools>=67.0"]',
        'build-backend = "poetry.core.masonry.api"',
        "",
        "# Poetry version used by saf-cli to install the solution and by saf-desktop-installer to build it.",
        "[build-system-requirements]",
        f"build-system-version = {toml_string(dependencies.poetry_version)}",
        "",
        "[saf-cli-version]",
        f"saf-cli-version = {toml_string(dependencies.saf_cli_version)}",
        "",
        "[tool.poetry]",
        f"name = {toml_string(PROJECT_NAME)}",
        'version = "0.0.0"',
        'description = ""',
        'license = "Proprietary"',
        f"authors = [{toml_string(f'{AUTHOR} <{AUTHOR_EMAIL}>')}]",
        'readme = "README.md"',
        'packages = [{ include = "saf", from = "src" }]',
        "",
        "[[tool.poetry.source]]",
        'name = "PyPI"',
        'priority = "primary"',
        "",
        "[tool.poetry.dependencies]",
        f"python = {toml_string(dependencies.requires_python)}",
    ]
    lines += [f"{toml_string(item.name)} = {poetry_value(item)}" for item in dependencies.groups["main"]]
    for group, items in dependencies.optional_groups.items():
        lines += ["", f"[tool.poetry.group.{group}]", "optional = true", f"[tool.poetry.group.{group}.dependencies]"]
        lines += [f"{toml_string(item.name)} = {poetry_value(item)}" for item in items]
    return HEADER + "\n".join(lines) + "\n"


def uv_pyproject(dependencies: Dependencies) -> str:
    """Return the UV ``pyproject.toml``."""

    def requirement_list(items: list[Requirement]) -> list[str]:
        return [f"    {toml_string(pep508(item))}," for item in items]

    lines = [
        "[build-system]",
        'requires = ["setuptools>=69", "wheel"]',
        'build-backend = "setuptools.build_meta"',
        "",
        "[project]",
        f"name = {toml_string(PROJECT_NAME)}",
        'version = "0.0.0"',
        'description = ""',
        'license = "LicenseRef-Proprietary"',
        f"authors = [{{ name = {toml_string(AUTHOR)}, email = {toml_string(AUTHOR_EMAIL)} }}]",
        'readme = "README.md"',
        f"requires-python = {toml_string(dependencies.requires_python)}",
        "dependencies = [",
        *requirement_list(dependencies.groups["main"]),
        "]",
        "",
        "[saf-cli-version]",
        f"saf-cli-version = {toml_string(dependencies.saf_cli_version)}",
        "",
        "[dependency-groups]",
    ]
    for group, items in dependencies.optional_groups.items():
        lines += [f"{group} = [", *requirement_list(items), "]"]
    lines += [
        "",
        "[tool.setuptools.packages.find]",
        'where = ["src"]',
        'include = ["saf*"]',
        "namespaces = true",
        "",
        "[tool.uv]",
        "package = true",
        'prerelease = "if-necessary"',
    ]
    return HEADER + "\n".join(lines) + "\n"


def pyproject_text(backend: str, dependencies: Dependencies | None = None) -> str:
    """Return the ``pyproject.toml`` of ``backend``."""
    dependencies = dependencies or Dependencies.load()
    if backend == "poetry":
        return poetry_pyproject(dependencies)
    if backend == "uv":
        return uv_pyproject(dependencies)
    raise ValueError(f"Unknown backend: {backend}")


def write_solution(backend: str, destination: Path, fixture: Path = FIXTURE_DIRECTORY, *, with_lock: bool = True) -> Path:
    """Write the complete solution of ``backend`` into ``destination`` and return it."""
    dependencies = Dependencies.load(fixture)
    shutil.copytree(fixture / "solution", destination, ignore=COPY_EXCLUSIONS)
    (destination / "pyproject.toml").write_text(pyproject_text(backend, dependencies), encoding="utf-8")
    if with_lock:
        lock = fixture / LOCK_FILES[backend]
        if not lock.is_file():
            raise FileNotFoundError(f"Lock file not found: {lock}. Run 'python fixture_builder.py --relock'.")
        shutil.copy2(lock, destination / LOCK_FILES[backend])
    return destination


def locked_versions(lock_file: Path) -> dict[str, list[str]]:
    """Return ``{package: sorted versions}`` from a Poetry or UV lock file."""
    versions: dict[str, set[str]] = {}
    for package in tomllib.loads(lock_file.read_text(encoding="utf-8")).get("package", []):
        if package["name"] == PROJECT_NAME:
            continue
        versions.setdefault(package["name"], set()).add(str(package["version"]))
    return {name: sorted(values) for name, values in sorted(versions.items())}


def version_differences(poetry_lock: Path, uv_lock: Path) -> dict[str, tuple[list[str], list[str]]]:
    """Return the packages whose locked versions differ between Poetry and UV."""
    poetry, uv = locked_versions(poetry_lock), locked_versions(uv_lock)
    return {
        name: (poetry.get(name, []), uv.get(name, []))
        for name in sorted(set(poetry) | set(uv))
        if poetry.get(name) != uv.get(name)
    }


def print_differences(differences: dict[str, tuple[list[str], list[str]]]) -> None:
    """Print version differences between the backends."""
    for name, (poetry, uv) in differences.items():
        print(f"  {name}: Poetry {', '.join(poetry) or '-'} / UV {', '.join(uv) or '-'}")


def lock_commands(backend: str, dependencies: Dependencies, upgrade: bool) -> list[str]:
    """Return the command that locks ``backend``."""
    uv = shutil.which("uv")
    if uv is None:
        raise FileNotFoundError("'uv' is required on PATH to lock the fixture (it also runs Poetry through uvx).")
    if backend == "uv":
        return [uv, "lock", *(["--upgrade"] if upgrade else [])]
    poetry = [uv, "tool", "run", "--from", f"poetry=={dependencies.poetry_version}", "poetry"]
    return [*poetry, "lock", *(["--regenerate"] if upgrade else [])]


def relock(upgrade: bool) -> int:
    """Lock both backends and write the locks only when their versions match."""
    dependencies = Dependencies.load()
    with tempfile.TemporaryDirectory(prefix="saf-benchmark-lock-") as temporary:
        root = Path(temporary)
        new_locks: dict[str, Path] = {}
        for backend in BACKENDS:
            project = write_solution(backend, root / backend, with_lock=False)
            current = FIXTURE_DIRECTORY / LOCK_FILES[backend]
            if current.is_file():
                shutil.copy2(current, project / LOCK_FILES[backend])
            environment = os.environ.copy()
            # Keep Poetry's virtual environment out of the user's cache and the project in-tree.
            environment["POETRY_VIRTUALENVS_IN_PROJECT"] = "true"
            print(f"Locking {backend}...", flush=True)
            subprocess.run(lock_commands(backend, dependencies, upgrade), cwd=project, env=environment, check=True)
            new_locks[backend] = project / LOCK_FILES[backend]

        differences = version_differences(new_locks["poetry"], new_locks["uv"])
        if differences:
            print("Poetry and UV resolved different versions; the locks were NOT updated:")
            print_differences(differences)
            print("Pin the listed packages in dependencies.toml, then run --relock again.")
            return 1
        for backend, lock in new_locks.items():
            shutil.copy2(lock, FIXTURE_DIRECTORY / LOCK_FILES[backend])
        count = len(locked_versions(new_locks["uv"]))
        print(f"Updated poetry.lock and uv.lock: {count} packages, identical versions in both.")
    return 0


def check() -> int:
    """Verify that the committed locks exist and pin identical versions."""
    locks = {backend: FIXTURE_DIRECTORY / LOCK_FILES[backend] for backend in BACKENDS}
    missing = [str(path) for path in locks.values() if not path.is_file()]
    if missing:
        print(f"Missing lock files: {', '.join(missing)}")
        return 1
    differences = version_differences(locks["poetry"], locks["uv"])
    if differences:
        print("poetry.lock and uv.lock pin different versions:")
        print_differences(differences)
        return 1
    print(f"poetry.lock and uv.lock pin the same versions ({len(locked_versions(locks['uv']))} packages).")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--relock", action="store_true", help="Lock both backends after editing dependencies.toml.")
    action.add_argument("--check", action="store_true", help="Verify that both locks pin the same versions.")
    action.add_argument(
        "--write",
        nargs=2,
        metavar=("BACKEND", "DIRECTORY"),
        help="Write the complete solution of BACKEND (poetry or uv) into DIRECTORY, e.g. to inspect it.",
    )
    parser.add_argument("--upgrade", action="store_true", help="With --relock: resolve the latest allowed versions.")
    arguments = parser.parse_args(argv)
    if arguments.relock:
        return relock(arguments.upgrade)
    if arguments.check:
        return check()
    backend, directory = arguments.write
    if backend not in BACKENDS:
        parser.error(f"BACKEND must be one of: {', '.join(BACKENDS)}")
    print(write_solution(backend, Path(directory)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
