"""Names, tags, and sections shared by the items, templates, and exports of the ADR reference report.

The report contains one section per common ADR item type. Each section is rendered by its own
template, which shows a short explanation of the item type followed by an example item.
"""

from dataclasses import dataclass

REPORT_TITLE = "ADR Reference Report"
"""Title displayed at the top of the report."""

REPORT_TEMPLATE_NAME = "adr-reference-report"
"""Name of the root template used to render the report as HTML and PDF."""

PPTX_TEMPLATE_NAME = "adr-reference-pptx-report"
"""Name of the PPTX layout template used to export the report as a PowerPoint presentation."""

PPTX_INPUT_ITEM_NAME = "adr-reference-pptx-input.pptx"
"""Name of the File item holding the input PowerPoint deck used by the PPTX layout template."""

REPORT_TAG = "adr_reference"
"""Tag set on every item of the report, so that they never mix with items of other reports."""


@dataclass(frozen=True)
class ReportSection:
    """Section of the report showing one ADR item type."""

    item_type: str
    """ADR item type shown in the section, for example ``string``."""

    title: str
    """Title of the section."""

    description: str
    """Plain-text explanation of the item type, shown above the example item."""

    @property
    def item_name(self) -> str:
        """Name of the example item shown in the section."""
        return f"adr-reference-{self.item_type}"

    @property
    def template_name(self) -> str:
        """Name of the template rendering the section, also displayed in the table of contents."""
        return self.title


STRING_SECTION = ReportSection(
    item_type="string",
    title="String item",
    description="A String item stores plain, unformatted text. "
    "Use it for short notes, labels, or messages generated by your workflow.",
)

HTML_SECTION = ReportSection(
    item_type="html",
    title="HTML item",
    description="An HTML item stores a fragment of HTML markup. "
    "Use it for rich text such as headings, emphasized text, lists, or links.",
)

TABLE_SECTION = ReportSection(
    item_type="table",
    title="Table item",
    description="A Table item stores a two-dimensional array of numbers or strings with optional row and "
    "column labels. Use it for input parameters or numerical results.",
)

TREE_SECTION = ReportSection(
    item_type="tree",
    title="Tree item",
    description="A Tree item stores hierarchical data as nested nodes, each with a name and a value. "
    "Use it for structured information such as simulation settings.",
)

IMAGE_SECTION = ReportSection(
    item_type="image",
    title="Image item",
    description="An Image item stores a PNG, JPG, or TIFF picture. "
    "Use it for plots, screenshots, or contour pictures of your results.",
)

SCENE_SECTION = ReportSection(
    item_type="scene",
    title="Scene item",
    description="A Scene item stores a 3D geometry file (STL, PLY, AVZ, GLB, OBJ, and more). "
    "Use it to show a model that readers can explore in 3D.",
)

FILE_SECTION = ReportSection(
    item_type="file",
    title="File item",
    description="A File item stores any file. "
    "Use it to attach input decks or result files that readers can download from the report.",
)

REPORT_SECTIONS: tuple[ReportSection, ...] = (
    STRING_SECTION,
    HTML_SECTION,
    TABLE_SECTION,
    TREE_SECTION,
    IMAGE_SECTION,
    SCENE_SECTION,
    FILE_SECTION,
)
"""Sections of the report, in display order."""


def build_project_tag(project_id: str) -> str:
    """Build the tag identifying the items of a given project."""
    return f"project={project_id}"


def build_item_tags(project_tag: str) -> str:
    """Build the tags set on every item of the report of a project."""
    return f"{REPORT_TAG} {project_tag}"


def build_item_filter(project_tag: str) -> str:
    """Build the ADR query selecting only the report items of a project."""
    return f"A|i_tags|cont|{REPORT_TAG};A|i_tags|cont|{project_tag};"
