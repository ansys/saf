"""Items of the ADR reference report.

Each function creates the example item of one section of the report and saves it in the ADR database.
The examples use placeholder content: replace it with your own data to build a real report.

Items are created with ``adr.create_item(<ItemType>, name=..., content=..., tags=...)``. The tags are
used to select the items of a given project when rendering the report.
"""

from dataclasses import dataclass
import logging
from pathlib import Path

from ansys.dynamicreporting.core.serverless import ADR, HTML, File, Image, Item, Scene, String, Table, Tree
import numpy as np

from saf.solutions.examples.solution.logic.adr_reference.report_definition import (
    FILE_SECTION,
    HTML_SECTION,
    IMAGE_SECTION,
    SCENE_SECTION,
    STRING_SECTION,
    TABLE_SECTION,
    TREE_SECTION,
    build_item_filter,
    build_item_tags,
)

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class ReportItemFiles:
    """Local files used as content of the file-based report items."""

    image: Path
    scene: Path
    file: Path


def create_string_item(adr: ADR, tags: str) -> Item:
    """Create the example String item."""
    return adr.create_item(
        String,
        name=STRING_SECTION.item_name,
        content="This is a placeholder String item. Replace this text with a message generated by your workflow.",
        tags=tags,
    )


def create_html_item(adr: ADR, tags: str) -> Item:
    """Create the example HTML item.

    The PowerPoint export only supports non-nested ``<h1>`` to ``<h6>``, ``<a>``, and ``<br>`` tags,
    so the example sticks to them. Other tags are fine for HTML and PDF reports.
    """
    content = (
        "<h3>Placeholder HTML item</h3>"
        "This text is formatted with HTML markup.<br>"
        "Learn more in the "
        '<a href="https://dynamicreporting.docs.pyansys.com/" target="_blank">PyDynamicReporting documentation</a>.'
    )
    return adr.create_item(HTML, name=HTML_SECTION.item_name, content=content, tags=tags)


def create_table_item(adr: ADR, tags: str) -> Item:
    """Create the example Table item."""
    time = np.linspace(0.0, 1.0, 5)
    displacement = 2.0 * time
    stress = 150.0 * time
    table_item = adr.create_item(
        Table,
        name=TABLE_SECTION.item_name,
        content=np.column_stack((time, displacement, stress)),
        tags=tags,
    )
    table_item.labels_row = [f"Step {index + 1}" for index in range(len(time))]
    table_item.labels_column = ["Time [s]", "Displacement [mm]", "Stress [MPa]"]
    table_item.format = "floatdot2"
    table_item.save()
    return table_item


def create_tree_item(adr: ADR, tags: str) -> Item:
    """Create the example Tree item."""
    content = [
        {
            "key": "simulation",
            "name": "Simulation settings",
            "value": "Placeholder values",
            "children": [
                {"key": "solver", "name": "Solver", "value": "Static structural"},
                {
                    "key": "mesh",
                    "name": "Mesh",
                    "value": "",
                    "children": [
                        {"key": "element_size", "name": "Element size [mm]", "value": 5.0},
                        {"key": "element_count", "name": "Element count", "value": 12500},
                    ],
                },
                {"key": "converged", "name": "Converged", "value": True},
            ],
        },
    ]
    return adr.create_item(Tree, name=TREE_SECTION.item_name, content=content, tags=tags)


def create_image_item(adr: ADR, tags: str, image_path: Path) -> Item:
    """Create the example Image item from a PNG, JPG, or TIFF file."""
    return adr.create_item(Image, name=IMAGE_SECTION.item_name, content=str(image_path), tags=tags)


def create_scene_item(adr: ADR, tags: str, scene_path: Path) -> Item:
    """Create the example Scene item from a 3D geometry file.

    The report displays scenes in AVZ format. AVZ files are used as is, while other formats (STL, PLY,
    OBJ, ...) are converted with the ``cei_apex<version>_udrw2avz`` tool of the ADR installation, which
    must then be found on the ``PATH`` (for example ``C:\\Program Files\\ANSYS Inc\\v271\\ADR\\bin``).
    """
    return adr.create_item(Scene, name=SCENE_SECTION.item_name, content=str(scene_path), tags=tags)


def create_file_item(adr: ADR, tags: str, file_path: Path) -> Item:
    """Create the example File item from any file."""
    return adr.create_item(File, name=FILE_SECTION.item_name, content=str(file_path), tags=tags)


def create_report_items(adr: ADR, project_tag: str, files: ReportItemFiles) -> None:
    """Create the example items of every section of the report for a project."""
    tags = build_item_tags(project_tag)
    logger.info("Creating the ADR reference report items (tags: %s).", tags)
    create_string_item(adr, tags)
    create_html_item(adr, tags)
    create_table_item(adr, tags)
    create_tree_item(adr, tags)
    create_image_item(adr, tags, files.image)
    create_scene_item(adr, tags, files.scene)
    create_file_item(adr, tags, files.file)


def delete_report_items(adr: ADR, project_tag: str) -> None:
    """Delete the report items previously created for a project, together with their media files."""
    items = adr.query(Item, query=build_item_filter(project_tag))
    if items:
        logger.info("Deleting %d existing ADR reference report items (%s).", len(items), project_tag)
        items.delete()
